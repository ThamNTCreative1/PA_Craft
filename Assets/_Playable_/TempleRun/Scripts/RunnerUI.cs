using TMPro;
using UnityEngine;
using UnityEngine.UI;

namespace Playable.TempleRun
{
    public class RunnerUI : MonoBehaviour
    {
        [Header("HUD")]
        public TMP_Text coinText;
        public RectTransform coinIcon;
        public GameObject countdownRoot;
        public TMP_Text countdownText;

        [Header("Distance HUD")]
        public TMP_Text distanceText;

        public void SetDistance(float meters)
        {
            _meters = meters;
            if (distanceText != null)
                distanceText.text = Mathf.FloorToInt(Mathf.Max(0f, meters)) + " M";
        }

        [Header("Tutorial hands")]
        public GameObject moveHandRoot;
        public RectTransform moveHand;
        public GameObject jumpHandRoot;
        public RectTransform jumpHand;
        public float moveHandRange = 230f;
        public float jumpHandRange = 260f;

        [Header("End")]
        public GameObject endPanel;
        public TMP_Text endTitleText;
        public TMP_Text endCoinsText;
        public Button endCtaButton;
        public Button endBackgroundButton;
        public string winTitle = "GREAT RUN!";
        public string loseTitle = "CAUGHT!";

        [Header("Fail panel (authored in scene)")]
        public GameObject failPanel;
        public TMP_Text failCoinsText, failDistanceText;
        public Button failCtaButton;

        [Header("Responsive layout")]
        public RectTransform safeRoot, resultSafeRoot, hudCounter, endCard, endBadge, endCounter;
        public RectTransform moveContent, jumpContent;
        public TMP_Text endDistanceText, endMetersText, retryCountText;
        public Button retryButton;
        public Image endCardImage, endBadgeImage, endTitleImage;
        public Sprite winTitleSprite, failTitleSprite;
        public Sprite winPanelSprite, failPanelSprite, winBadgeSprite, failBadgeSprite;
        public Image bloodSplash;
        public Image bloodScreenTint;
        public Image[] bloodSpots;
        public float bloodSplashDuration = 0.65f;
        private float _bloodTime = -1f;
        private float _meters;

        public void ShowBloodSplash()
        {
            _bloodTime = 0f;
            if (bloodSplash == null) return;
            bloodSplash.gameObject.SetActive(true);
            bloodSplash.transform.SetAsLastSibling();
            bloodSplash.enabled = false;
            if (bloodScreenTint != null) bloodScreenTint.gameObject.SetActive(false);
            UpdateBloodSpots(0f);
        }

        private void UpdateBloodSpots(float t)
        {
            if (bloodSpots == null) return;
            float fade = 1f - Mathf.Clamp01((t - 0.65f) / 0.35f);
            for (int i = 0; i < bloodSpots.Length; i++)
            {
                Image spot = bloodSpots[i];
                if (spot == null) continue;
                float delay = (i % 5) * 0.035f;
                // Preserve the authored RectTransform; animate visibility only.
                float burst = Mathf.Clamp01((t - delay) / 0.08f);
                Color color = spot.color;
                color.a = 0.9f * burst * fade;
                spot.color = color;
            }
        }

        private void HideBloodSplash()
        {
            _bloodTime = -1f;
            if (bloodSplash != null) bloodSplash.gameObject.SetActive(false);
        }



        private float _coinPunch;
        private Vector3 _coinIconBaseScale = Vector3.one;
        private Quaternion _moveHandBaseRotation = Quaternion.identity;
        private Vector2 _moveHandBase;
        private Vector2 _jumpHandBase;
        private Image _jumpHandImage;
        private float _handTime;
        private int _lastSeconds = -1;

        private void Awake()
        {
            // Match the mesh layout generated by the target TMP implementation.
            TMP_Text[] labels = GetComponentsInChildren<TMP_Text>(true);
            for (int i = 0; i < labels.Length; i++)
            {
                Material material = labels[i].fontSharedMaterial;
                if (material == null || !material.HasProperty("_LunaLegacyUV")) continue;
#if TR_LUNA_TMP_UV
                material.SetFloat("_LunaLegacyUV", 1f);
#else
                material.SetFloat("_LunaLegacyUV", 0f);
#endif
            }


            if (coinIcon != null) _coinIconBaseScale = coinIcon.localScale;
            if (moveHand != null)
            {
                _moveHandBase = moveHand.anchoredPosition;
                _moveHandBaseRotation = moveHand.localRotation;
            }
            if (jumpHand != null)
            {
                _jumpHandBase = jumpHand.anchoredPosition;
                _jumpHandImage = jumpHand.GetComponent<Image>();
            }
        }

        public void SetCoins(int coins)
        {
            if (coinText != null) coinText.text = coins.ToString();
            _coinPunch = 1f;
        }

        public void ShowMoveHand(bool show)
        {
            if (moveHandRoot != null) moveHandRoot.SetActive(show);
            _handTime = 0f;
        }

        public void ShowJumpHand(bool show)
        {
            if (jumpHandRoot != null && jumpHandRoot.activeSelf != show)
            {
                jumpHandRoot.SetActive(show);
                _handTime = 0f;
            }
        }

        public void ShowCountdown(bool show)
        {
            if (countdownRoot != null) countdownRoot.SetActive(show);
            _lastSeconds = -1;
        }

        public void SetCountdown(float seconds)
        {
            int s = Mathf.Max(0, Mathf.CeilToInt(seconds));
            if (s == _lastSeconds || countdownText == null) return;
            _lastSeconds = s;
            countdownText.text = (s / 60) + ":" + (s % 60).ToString("00");
        }

        public void ShowEnd(int coins, bool win, int replaysRemaining = 0)
        {
            HideBloodSplash();
            if (moveHandRoot != null) moveHandRoot.SetActive(false);
            if (jumpHandRoot != null) jumpHandRoot.SetActive(false);
            if (endPanel != null) endPanel.SetActive(win);
            if (failPanel != null) failPanel.SetActive(!win);
            TMP_Text coinsLabel = win ? endCoinsText : failCoinsText;
            TMP_Text distanceLabel = win ? endDistanceText : failDistanceText;
            if (coinsLabel != null) coinsLabel.text = coins.ToString();
            if (distanceLabel != null) distanceLabel.text = Mathf.FloorToInt(Mathf.Max(0f, _meters)).ToString();
            bool canReplay = !win && replaysRemaining > 0;
            // Keep Play Again visible on failure; the manager routes it to CTA when exhausted.
            if (retryButton != null) retryButton.gameObject.SetActive(!win);
            if (failCtaButton != null) failCtaButton.gameObject.SetActive(!win && !canReplay);
        }

        public void HideEndPanels()
        {
            HideBloodSplash();
            if (endPanel != null) endPanel.SetActive(false);
            if (failPanel != null) failPanel.SetActive(false);
        }

        // Layout is authored in the scene, including the shared win/fail panel.
        public void RefreshLayout() { }

        private void Update()
        {

    
            float udt = Time.unscaledDeltaTime;
            _handTime += udt;
            if (_bloodTime >= 0f && bloodSplash != null)
            {
                _bloodTime += udt;
                float t = Mathf.Clamp01(_bloodTime / Mathf.Max(0.1f, bloodSplashDuration));
                UpdateBloodSpots(t);
                if (t >= 1f) HideBloodSplash();
            }

            if (coinIcon != null)
            {
                _coinPunch = Mathf.MoveTowards(_coinPunch, 0f, udt * 5f);
                float s = 1f + 0.35f * _coinPunch;
                coinIcon.localScale = new Vector3(_coinIconBaseScale.x * s, _coinIconBaseScale.y * s, _coinIconBaseScale.z);
            }

            // hand swiping left <-> right (ease in/out)
            if (moveHand != null && moveHandRoot != null && moveHandRoot.activeSelf)
            {
                float x = Mathf.Sin(_handTime * 3.2f) * moveHandRange;
                moveHand.anchoredPosition = _moveHandBase + new Vector2(x, 0f);
                moveHand.localRotation = _moveHandBaseRotation * Quaternion.Euler(0f, 0f, moveHandRange != 0f ? -x / moveHandRange * 12f : 0f);
            }

            // hand swiping up: slide up + fade, repeat
            if (jumpHand != null && jumpHandRoot != null && jumpHandRoot.activeSelf)
            {
                float t = Mathf.Repeat(_handTime / 0.9f, 1f);
                float e = 1f - (1f - t) * (1f - t);
                jumpHand.anchoredPosition = _jumpHandBase + new Vector2(0f, e * jumpHandRange);
                if (_jumpHandImage != null)
                {
                    Color c = _jumpHandImage.color;
                    c.a = t < 0.75f ? 1f : 1f - (t - 0.75f) / 0.25f;
                    _jumpHandImage.color = c;
                }
            }

        }
    }
}
